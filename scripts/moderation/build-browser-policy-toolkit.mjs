import { createHash } from 'node:crypto';
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(resolve(root, 'tfpphotographers/packages/moderation/package.json'));
const ts = require('typescript');
const runtimePath = 'tfpphotographers/packages/moderation/src/raw-policy/runtime.ts';
const sourcePath = 'tfp-moderation-service/tooling/browser-policy-toolkit.source.js';
const outputPath = 'tfp-moderation-service/src/tfp_moderation_service/static/browser_policy_evaluator_toolkit.js';

export function generateToolkit() {
  const runtime = fs.readFileSync(resolve(root, runtimePath), 'utf8');
  const source = fs.readFileSync(resolve(root, sourcePath), 'utf8');
  const tree = ts.createSourceFile(runtimePath, runtime, ts.ScriptTarget.Latest, true);
  const factories = tree.statements.filter((node) => ts.isFunctionDeclaration(node)
    && node.name?.text === 'createRawPolicyRuntime');
  if (factories.length !== 1) throw new Error('Expected one canonical runtime factory');
  const factory = factories[0];
  const localFactory = ts.factory.updateFunctionDeclaration(factory,
    factory.modifiers?.filter((modifier) => modifier.kind !== ts.SyntaxKind.ExportKeyword),
    factory.asteriskToken, factory.name, factory.typeParameters, factory.parameters, factory.type, factory.body);
  // TypeScript's own compiler erases types. No handwritten parser or evaluator is generated.
  const compiled = ts.transpileModule(ts.createPrinter().printNode(ts.EmitHint.Unspecified, localFactory, tree), {
    compilerOptions: { target: ts.ScriptTarget.ES2018, module: ts.ModuleKind.None },
    reportDiagnostics: true,
  });
  if (compiled.diagnostics?.some((diagnostic) => diagnostic.category === ts.DiagnosticCategory.Error)) {
    throw new Error('Canonical runtime could not be compiled');
  }
  const marker = '/* CANONICAL_RAW_POLICY_RUNTIME */';
  if (source.split(marker).length !== 2) throw new Error('Expected one runtime insertion point');
  const digest = (value) => createHash('sha256').update(value).digest('hex');
  return `// Generated by scripts/moderation/build-browser-policy-toolkit.mjs. Do not edit.\n`
    + `// runtime sha256: ${digest(runtime)}; report source sha256: ${digest(source)}\n`
    + source.replace(marker, compiled.outputText.trim().split('\n').join('\n  '));
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = generateToolkit();
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(resolve(root, outputPath), 'utf8') !== output) {
      throw new Error('Browser toolkit is stale; run this script without --check');
    }
    console.log('Browser toolkit matches the canonical runtime and report source');
  } else {
    fs.writeFileSync(resolve(root, outputPath), output);
    console.log(`Generated ${outputPath}`);
  }
}
